/**
 * Writes `docs/generated/` from the product, so the site never carries a second copy
 * of what the code and the registry already state:
 *
 *   cli.md         the usage table at the top of `packages/regulator/src/cli.ts`
 *   regulators.md  `packages/regulator/registry/REGULATORS.md` (rendered from the registry by `regulator docs`)
 *   boundary.md    `packages/regulator/BOUNDARY.md`
 *   operating.md   `packages/regulator/OPERATING.md`
 *   changelog.md   `packages/regulator/CHANGELOG.md`
 *
 * Relative links in a copied file are re-based: a target inside `docs/` is linked
 * relative to the page's rewritten location; anything else links into the repository
 * on GitHub. Run by `pnpm --filter regulator-docs build` and `dev`.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const DOCS = fileURLToPath(new URL("..", import.meta.url));
const ROOT = path.resolve(DOCS, "..");
const PRODUCT = path.join(ROOT, "packages", "regulator");
const OUT = path.join(DOCS, "generated");
const REPO = "https://github.com/MetaCoding-io/regulator/blob/main";

/** Where `.vitepress/config.ts` rewrites each generated page to; links are re-based against that location. */
const PLACEMENT = {
  "cli.md": "reference/cli.md",
  "regulators.md": "reference/regulators.md",
  "boundary.md": "reference/boundary.md",
  "operating.md": "guide/operating.md",
  "changelog.md": "project/changelog.md",
};

const banner = (source) => `<!-- Generated by docs/scripts/generate.mjs from ${source}. Do not edit here. -->\n\n`;

/** Vue's template compiler reads `<definition>` in prose as a tag; escape `<` outside code spans and fences. */
function escapeAngles(markdown) {
  let fenced = false;
  return markdown.split("\n").map((line) => {
    if (/^\s*(```|~~~)/.test(line)) { fenced = !fenced; return line; }
    if (fenced) return line;
    return line.split(/(`[^`]*`)/).map((part, i) => (i % 2 ? part : part.replace(/<(?=[A-Za-z/])/g, "&lt;"))).join("");
  }).join("\n");
}

function rebaseLinks(markdown, sourceDir, placedAt) {
  const placedDir = path.dirname(path.join(DOCS, placedAt));
  return markdown.replace(/\]\((\.\.?\/[^)\s]+)\)/g, (whole, href) => {
    const [target, hash] = href.split("#");
    const absolute = path.resolve(sourceDir, target);
    const suffix = hash ? `#${hash}` : "";
    if (absolute.startsWith(DOCS)) {
      let rel = path.relative(placedDir, absolute).split(path.sep).join("/");
      if (!rel.startsWith(".")) rel = `./${rel}`;
      return `](${rel}${suffix})`;
    }
    return `](${REPO}/${path.relative(ROOT, absolute).split(path.sep).join("/")}${suffix})`;
  });
}

/** The usage table: `regulator <synopsis>   <description>` lines under group headings, inside the file's first doc comment. */
function parseUsage(source) {
  const comment = source.slice(source.indexOf("/**"), source.indexOf("*/"));
  const lines = comment.split("\n").slice(1).map((l) => l.replace(/^\s*\*\s?/, ""));
  const groups = [];
  let group = null;
  let entry = null;
  const trailing = [];
  let seenTitle = false;
  let inTrailing = false;
  for (const raw of lines) {
    if (!raw.trim()) { entry = null; continue; }
    const indented = /^\s/.test(raw);
    const line = raw.trim();
    if (!indented) {
      if (!seenTitle) { seenTitle = true; continue; } // the title line
      // A short line with no punctuation is a group heading; a sentence is the trailing note.
      if (!inTrailing && line.length < 40 && !/[.:`]/.test(line)) { group = { name: line, entries: [] }; groups.push(group); continue; }
      inTrailing = true;
      trailing.push(line);
      continue;
    }
    if (!group || inTrailing) continue;
    if (line.startsWith("regulator ")) {
      const m = /^(regulator .*?)\s{3,}(.*)$/.exec(line);
      entry = m ? { synopsis: m[1], description: m[2] } : { synopsis: line, description: "" };
      group.entries.push(entry);
    } else if (entry) {
      const m = /^(\S.*?)\s{3,}(.*)$/.exec(line);
      if (m && /^[\[<-]/.test(m[1])) { entry.synopsis += ` ${m[1]}`; entry.description += ` ${m[2]}`; }
      else entry.description += ` ${line}`;
    }
  }
  return { groups, trailing };
}

function renderCli(source) {
  const { groups, trailing } = parseUsage(source);
  const out = ["# CLI", "", "`regulator` is the `bin` of `@metacoding/regulator`. Every command runs against the instance in the current working directory (the base checkout `regulator init` was run in) and the definition that ships with the package; `--policy`, `--recovery`, `--routing` and `--interaction` point a command at a different policy file for one run.", "", "```sh", "pnpm add -D @metacoding/regulator @metacoding/regulator-pi", "pnpm regulator doctor", "```", ""];
  for (const g of groups) {
    out.push(`## ${g.name}`, "");
    for (const e of g.entries) {
      out.push(`### \`${e.synopsis.replace(/^regulator /, "")}\``, "", `\`\`\`sh\n${e.synopsis}\n\`\`\``, "", e.description.trim().replace(/^./, (c) => c.toUpperCase()), "");
    }
  }
  if (trailing.length) out.push("## Authority", "", trailing.join(" "), "");
  out.push("## The definition's own commands", "", "The definition check and the generated registry documents are a second entry point, `registry-cli.js` in the same package, run from the workspace:", "", "```sh", "pnpm --filter @metacoding/regulator registry:check   # validate the registry and the definition; exit 1 on a problem", "pnpm --filter @metacoding/regulator registry:docs    # rewrite registry/REGULATORS.md and BOUNDARY.md", "```", "", "`registry:check` runs under `pnpm check`, so a record whose review date has passed fails the build.", "");
  return out.join("\n");
}

async function copy(source, name, title) {
  let text = await readFile(source, "utf8");
  if (title) text = text.replace(/^# .*\n/, `# ${title}\n`);
  text = escapeAngles(rebaseLinks(text, path.dirname(source), PLACEMENT[name]));
  await writeFile(path.join(OUT, name), banner(path.relative(ROOT, source)) + text);
}

await mkdir(OUT, { recursive: true });
const cliSource = await readFile(path.join(PRODUCT, "src", "cli.ts"), "utf8");
await writeFile(path.join(OUT, "cli.md"), banner("packages/regulator/src/cli.ts") + renderCli(cliSource));
await copy(path.join(PRODUCT, "registry", "REGULATORS.md"), "regulators.md");
await copy(path.join(PRODUCT, "BOUNDARY.md"), "boundary.md");
await copy(path.join(PRODUCT, "OPERATING.md"), "operating.md", "Operating");
await copy(path.join(PRODUCT, "CHANGELOG.md"), "changelog.md");
console.log(`generated ${Object.keys(PLACEMENT).length} pages into ${path.relative(ROOT, OUT)}/`);
